alter table public.site_content enable row level security;
alter table public.news enable row level security;
alter table public.owner_access enable row level security;

-- Public website can read content/news; only an approved owner email can change them.
create policy "public read site content" on public.site_content for select using (true);
create policy "public read news" on public.news for select using (true);
create policy "owner read access list" on public.owner_access for select using (
  lower(coalesce(auth.jwt()->>'email','')) = lower(email)
);

create policy "approved owner insert content" on public.site_content for insert with check (
  exists (select 1 from public.owner_access a where lower(a.email)=lower(auth.jwt()->>'email') and a.enabled=true)
);
create policy "approved owner update content" on public.site_content for update using (
  exists (select 1 from public.owner_access a where lower(a.email)=lower(auth.jwt()->>'email') and a.enabled=true)
) with check (
  exists (select 1 from public.owner_access a where lower(a.email)=lower(auth.jwt()->>'email') and a.enabled=true)
);
create policy "approved owner delete content" on public.site_content for delete using (
  exists (select 1 from public.owner_access a where lower(a.email)=lower(auth.jwt()->>'email') and a.enabled=true)
);

