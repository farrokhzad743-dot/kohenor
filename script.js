track.addEventListener('scroll',()=>{
  const cards=[...track.querySelectorAll('.news-card')];
  if(!cards.length)return;

  const trackRect=track.getBoundingClientRect();
  const center=trackRect.left+trackRect.width/2;
  let best=0,dist=Infinity;

  cards.forEach((c,i)=>{
    const r=c.getBoundingClientRect();
    const d=Math.abs(r.left+r.width/2-center);
    if(d<dist){
      dist=d;
      best=i;
    }
  });

  setActiveDot(best);
},{passive:true});

function renderDoc(i=0){
  const d=docs[i];
  viewer.innerHTML=
    `<img src="${d.url}" alt="${esc(d.title)}" loading="lazy">
     <div class="document-caption">
       <strong>${esc(d.title)}</strong><br>
       تصویر سند رسمی ارائه‌شده در بخش اسناد و مدارک.
     </div>`;

  document.querySelectorAll('.document-tab')
    .forEach((b,j)=>b.classList.toggle('active',j===i));
}

document.querySelectorAll('.document-tab')
  .forEach(b=>b.onclick=()=>renderDoc(Number(b.dataset.doc)));

