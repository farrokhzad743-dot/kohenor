document.addEventListener('keydown',e=>{
  if(e.key==='Escape'){
    ['newsModal','articleModal','contentModal','lightboxModal']
      .forEach(closeModal);
  }

  if(document.getElementById('lightboxModal')?.classList.contains('open')){
    if(e.key==='ArrowLeft'){
      showLightboxImage(currentLightboxIndex+1);
      startLightboxTimer();
    }
    if(e.key==='ArrowRight'){
      showLightboxImage(currentLightboxIndex-1);
      startLightboxTimer();
    }
    return;
  }

  if(e.key==='ArrowLeft'){
    goToNews(activeNews+1);
    restartTimer();
  }

  if(e.key==='ArrowRight'){
    goToNews(activeNews-1);
    restartTimer();
  }
});

