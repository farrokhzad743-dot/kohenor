function esc(value) {
  return String(value ?? '').replace(/[&<>"']/g, char => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;'
  }[char]));
}

function imageCacheKey(pageUrl) {
  return 'kohenor-img:' + pageUrl;
}

function cachedImageUrl(pageUrl) {
  try { return localStorage.getItem(imageCacheKey(pageUrl)) || ''; } catch (_) { return ''; }
}

function saveImageUrl(pageUrl, imageUrl) {
  try { localStorage.setItem(imageCacheKey(pageUrl), imageUrl); } catch (_) {}
}

function directImageFromText(text) {
  const patterns = [
    /https:\/\/i\.ibb\.co\/[A-Za-z0-9._\/-]+/i,
    /https:\/\/[A-Za-z0-9.-]+\/(?:[^\s)\]"']+\.(?:jpg|jpeg|png|webp|gif))(?:\?[^\s)\]"']*)?/i
  ];
  for (const pattern of patterns) {
    const match = String(text || '').match(pattern);
    if (match) return match[0].replace(/[),.;]+$/g, '');
  }
  return '';
}

async function resolveMediaUrl(pageUrl) {
  if (!pageUrl) return '';
  if (/\.(?:jpg|jpeg|png|webp|gif)(?:[?#].*)?$/i.test(pageUrl)) return pageUrl;

  const cached = cachedImageUrl(pageUrl);
  if (cached) return cached;

  if (!/https:\/\/ibb\.co\//i.test(pageUrl)) return pageUrl;

  try {
    const endpoint = 'https://r.jina.ai/' + pageUrl;
    const response = await fetch(endpoint, { cache: 'force-cache' });
    if (!response.ok) throw new Error('image resolver HTTP ' + response.status);
    const text = await response.text();
    const imageUrl = directImageFromText(text);
    if (imageUrl) {
      saveImageUrl(pageUrl, imageUrl);
      return imageUrl;
    }
  } catch (error) {
    console.warn('Could not resolve image:', pageUrl, error);
  }

  return '';
}

async function hydrateImage(img, pageUrl) {
  const direct = await resolveMediaUrl(pageUrl);
  if (direct) {
    img.src = direct;
    img.dataset.resolved = '1';
    return true;
  }
  img.classList.add('image-failed');
  return false;
}

